def create_joints_from_hierarchy(scene, root_node, joint_hierarchy):
    """从层次结构创建关节"""
    joints = {}
    
    # 按依赖顺序创建关节
    created_joints = set()
    
    def create_joint_recursive(joint_name):
        if joint_name in created_joints:
            return joints[joint_name]
        
        joint_info = joint_hierarchy[joint_name]
        
        # 创建骨骼属性
        skeleton_attr = fbx.FbxSkeleton.Create(scene, f"{joint_name}_Skeleton")
        
        if joint_info['parent'] is None:
            # 根骨骼
            skeleton_attr.SetSkeletonType(fbx.FbxSkeleton.eRoot)
            skeleton_attr.Size.Set(1.0)
        else:
            # 肢体骨骼
            skeleton_attr.SetSkeletonType(fbx.FbxSkeleton.eLimbNode)
            skeleton_attr.Size.Set(1.0)
        
        # 创建节点
        joint_node = fbx.FbxNode.Create(scene, joint_name)
        joint_node.SetNodeAttribute(skeleton_attr)
        
        # 设置变换
        pos = joint_info['position']
        joint_node.LclTranslation.Set(fbx.FbxDouble3(pos[0], pos[1], pos[2]))
        joint_node.LclRotation.Set(fbx.FbxDouble3(0, 0, 0))
        joint_node.LclScaling.Set(fbx.FbxDouble3(1, 1, 1))
        
        # 设置节点属性
        joint_node.SetShadingMode(fbx.FbxNode.eWireFrame)
        joint_node.SetVisibility(True)
        
        joints[joint_name] = joint_node
        created_joints.add(joint_name)
        
        # 建立父子关系
        if joint_info['parent'] is None:
            root_node.AddChild(joint_node)
        else:
            parent_joint = create_joint_recursive(joint_info['parent'])
            parent_joint.AddChild(joint_node)
        
        print(f"  ✅ 创建关节: {joint_name}")
        return joint_node
    
    # 创建所有关节
    for joint_name in joint_hierarchy.keys():
        create_joint_recursive(joint_name)
    
    print(f"🎯 骨骼结构创建完成，共 {len(joints)} 个关节")
    return joints

def save_fbx_file_v7700(manager, scene, filename):
    """保存为FBX 2020版本（7700）"""
    print(f"💾 保存FBX文件: {filename}")
    
    # 创建导出器
    exporter = fbx.FbxExporter.Create(manager, "")
    
    # 设置导出格式为二进制FBX 2020
    format_index = -1
    format_count = manager.GetIOPluginRegistry().GetWriterFormatCount()
    
    for i in range(format_count):
        format_desc = manager.GetIOPluginRegistry().GetWriterFormatDescription(i)
        if "FBX binary" in format_desc and "2020" in format_desc:
            format_index = i
            break
    
    if format_index == -1:
        # 如果找不到2020格式，使用默认的二进制格式
        for i in range(format_count):
            format_desc = manager.GetIOPluginRegistry().GetWriterFormatDescription(i)
            if "FBX binary" in format_desc:
                format_index = i
                break
    
    # 初始化导出器
    if not exporter.Initialize(filename, format_index, manager.GetIOSettings()):
        print(f"❌ 无法初始化导出器: {exporter.GetStatus().GetErrorString()}")
        exporter.Destroy()
        return False
    
    # 设置导出选项
    ios = manager.GetIOSettings()
    ios.SetBoolProp(fbx.EXP_FBX_MATERIAL, True)
    ios.SetBoolProp(fbx.EXP_FBX_TEXTURE, True)
    ios.SetBoolProp(fbx.EXP_FBX_EMBEDDED, False)
    ios.SetBoolProp(fbx.EXP_FBX_SHAPE, True)
    ios.SetBoolProp(fbx.EXP_FBX_GOBO, True)
    ios.SetBoolProp(fbx.EXP_FBX_ANIMATION, True)
    ios.SetBoolProp(fbx.EXP_FBX_GLOBAL_SETTINGS, True)
    
    # 导出场景
    result = exporter.Export(scene)
    
    # 清理导出器
    exporter.Destroy()
    
    if result:
        print("✅ FBX文件保存成功")
        return True
    else:
        print("❌ FBX文件保存失败")
        return False

