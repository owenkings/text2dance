def create_maya_compatible_fbx(joints_data=None, output_file="maya_compatible_skeleton.fbx"):
    """创建Maya兼容的FBX文件"""
    print("🚀 创建Maya兼容的FBX文件...")
    
    # 创建FBX管理器
    manager = fbx.FbxManager.Create()
    if not manager:
        print("❌ 无法创建FBX管理器")
        return False
    
    # 创建IO设置 - 设置为FBX 2020版本（7700）
    ios = fbx.FbxIOSettings.Create(manager, fbx.IOSROOT)
    manager.SetIOSettings(ios)
    
    # 设置导出格式为FBX 2020
    ios.SetBoolProp(fbx.EXP_FBX_MATERIAL, True)
    ios.SetBoolProp(fbx.EXP_FBX_TEXTURE, True)
    ios.SetBoolProp(fbx.EXP_FBX_EMBEDDED, False)
    ios.SetBoolProp(fbx.EXP_FBX_SHAPE, True)
    ios.SetBoolProp(fbx.EXP_FBX_GOBO, True)
    ios.SetBoolProp(fbx.EXP_FBX_ANIMATION, True)
    ios.SetBoolProp(fbx.EXP_FBX_GLOBAL_SETTINGS, True)
    
    # 创建场景
    scene = fbx.FbxScene.Create(manager, "SkeletonScene")
    if not scene:
        print("❌ 无法创建FBX场景")
        manager.Destroy()
        return False
    
    # 设置场景信息
    scene_info = scene.GetSceneInfo()
    if scene_info:
        scene_info.mTitle = "Human Skeleton"
        scene_info.mSubject = "Generated by Python FBX SDK"
        scene_info.mAuthor = "FBX Generator"
        scene_info.mRevision = "1.0"
        scene_info.mKeywords = "skeleton, human, animation"
        scene_info.mComment = "Maya compatible skeleton file"
    
    print("✅ FBX管理器和场景创建成功")
    
    # 创建骨骼层次结构
    root_node = scene.GetRootNode()
    
    if joints_data:
        joints = create_skeleton_from_data(scene, root_node, joints_data)
    else:
        joints = create_default_skeleton(scene, root_node)
    
    # 设置全局设置
    global_settings = scene.GetGlobalSettings()
    global_settings.SetSystemUnit(fbx.FbxSystemUnit.cm)  # 使用厘米单位
    global_settings.SetOriginalUpAxis(fbx.FbxAxisSystem.MayaYUp)  # Maya Y轴向上
    global_settings.SetTimeMode(fbx.FbxTime.eFrames30)  # 30fps
    
    # 保存文件
    success = save_fbx_file_v7700(manager, scene, output_file)
    
    # 清理资源
    manager.Destroy()
    
    if success:
        print(f"🎉 Maya兼容FBX文件创建成功: {output_file}")
        # 检查文件大小
        if os.path.exists(output_file):
            file_size = os.path.getsize(output_file)
            print(f"📊 文件大小: {file_size:,} 字节")
        return True
    else:
        print("❌ FBX文件创建失败")
        return False

